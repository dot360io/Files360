/**
 * Writes every generated part of the docs from the code, so they cannot drift:
 *   docs/api.md                 the integration guide, for a sample app
 *   docs/public/openapi.json    the OpenAPI description
 *   docs/public/llms.txt        and llms-full.txt, for agents
 *   storage provider tables     in README.md and docs/storage.md
 *
 *   npm run docs:generate        write them
 *   npm run docs:generate -- --check   fail if anything is out of date (CI)
 */
process.env.PUBLIC_URL = 'https://files.example.com';
process.env.APP_NAME = 'Files360';

const fs = require('fs');
const path = require('path');
const { buildDocs } = require('../utils/docs');
const openapi = require('../utils/openapi');
const providers = require('../utils/providers');
const { DEFAULT_VARIANTS } = require('../db/apps');

const root = path.join(__dirname, '..');
const docs = path.join(root, 'docs');
const check = process.argv.includes('--check');
const stale = [];

function write(relative, content) {
  const file = path.join(root, relative);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) return;
  if (check) return stale.push(relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log(`wrote ${relative}`);
}

/** Replaces what sits between <!-- name:start --> and <!-- name:end --> in a file. */
function between(relative, name, content) {
  const file = path.join(root, relative);
  const text = fs.readFileSync(file, 'utf8');
  const start = `<!-- ${name}:start -->`;
  const end = `<!-- ${name}:end -->`;
  const a = text.indexOf(start);
  const b = text.indexOf(end);
  if (a === -1 || b === -1) throw new Error(`${relative} has no ${start} ... ${end} markers`);
  write(relative, `${text.slice(0, a + start.length)}\n${content}\n${text.slice(b)}`);
}

const GENERATED = '<!-- Generated by scripts/build-docs.js from the code. Edit the source, not this file. -->';

async function apiPage() {
  const sampleApp = {
    name: 'your app',
    slug: 'your-app',
    format: 'webp',
    quality: 80,
    maxUploadMB: 15,
    keepOriginal: false,
    allowDocuments: true,
    allowArchives: false,
    variants: DEFAULT_VARIANTS,
  };
  let markdown = await buildDocs(sampleApp);
  // The dashboard's guide is dated and per app; the public page is neither
  markdown = markdown
    .replace(/^# .*\n/, '# API reference\n')
    .replace(
      /^Integration guide generated on .*$/m,
      'Every app gets this guide in its dashboard with its own folder, sizes and limits filled in. The values below are the defaults of a new app called `your-app`. The machine-readable version is [openapi.json](/openapi.json).'
    );
  return `${GENERATED}\n\n${markdown}`;
}

function providerTable() {
  const anyReferral = providers.PROVIDERS.some((p) => p.referral);
  const rows = providers.PROVIDERS.map((p) => {
    const link = p.referral || p.site;
    const name = link ? `[${p.label} ${p.product}](${link})` : `${p.label} ${p.product}`;
    const regions = !p.regions ? 'your own endpoint' : p.regions.length > 4 ? `${p.regions.length} regions` : p.regions.map((r) => r.id).join(', ');
    const acl = p.supportsAcl === false ? 'Bucket-wide only' : 'Yes';
    return `| ${name} | ${p.blurb} | ${regions} | ${acl} |`;
  });
  const table = ['| Provider | | Regions | Per-object ACLs |', '| --- | --- | --- | --- |', ...rows].join('\n');
  const disclosure = anyReferral
    ? '\n\nLinks to storage providers are referral links. They cost you nothing, you still get the usual signup credit, and they help pay for the time that goes into this.'
    : '';
  return table + disclosure;
}

function llmsFull(llms) {
  const pages = ['install.md', 'configure.md', 'storage.md', 'api.md', 'security.md', 'migrating-from-cloudinary.md'];
  const bodies = pages
    .filter((p) => fs.existsSync(path.join(docs, p)))
    .map((p) =>
      fs
        .readFileSync(path.join(docs, p), 'utf8')
        .replace(/^---\n[\s\S]*?\n---\n/, '')
        .replace(/<!--[\s\S]*?-->\n*/g, '')
        .trim()
    );
  return `${llms}\n---\n\n${bodies.join('\n\n---\n\n')}\n`;
}

(async () => {
  write('docs/api.md', await apiPage());
  const table = providerTable();
  between('README.md', 'providers', table);
  between('docs/storage.md', 'providers', table);
  const site = 'https://your-files360.example.com';
  write('docs/public/openapi.json', `${JSON.stringify(openapi.spec(site), null, 2)}\n`);
  const llms = openapi.llmsTxt(site);
  write('docs/public/llms.txt', llms);
  write('docs/public/llms-full.txt', llmsFull(llms));

  if (stale.length) {
    console.error(`Out of date, run npm run docs:generate:\n  ${stale.join('\n  ')}`);
    process.exit(1);
  }
})().catch((err) => {
  console.error(err);
  process.exit(1);
});
